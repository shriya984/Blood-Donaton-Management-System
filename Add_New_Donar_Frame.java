  public boolean isValidAddhar (String addhar)
  {
      boolean flag=false;
      if(!addhar.isEmpty())
      {
          if(addhar.length()==12)
          {
              try
              {
                  long num=Long.parseLong(addhar);
                  flag=true;
              }
              catch(Exception ex)
                      {
                          System.out.println("Exception is:"+ex);
                      }
          }
      }
        return flag;
  }
  public boolean isValidAge(String age)
  {
      boolean flag=false;
      
      if(!age.isEmpty())
      {
          int a=Integer.parseInt(age);
          if(a>18)
          {
              try
              {
                  long num=Long.parseLong(age);
                  flag=true;
              }
              catch(Exception ex)
              {
                System.out.println(ex+"Exception is: "+ex);
              }
          }
      }
      return flag;
  }
  public boolean isValidEmail(String email)
    {
        boolean flag=false;
        if(!email.isEmpty())
        {
           if(email.contains("@")&&email.contains(".")) 
           {
               flag=true;
           }
        }
        return flag;
    }
