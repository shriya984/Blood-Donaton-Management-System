    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
         String name=jTextField1.getText();
       String email=jTextField2.getText();
       String mobile=jTextField3.getText();
       String address=jTextArea1.getText();
       String username=jTextField4.getText();
       char pass[]=jPasswordField1.getPassword();
       String password=String.valueOf(pass);
       char con[]=jPasswordField2.getPassword();
       String conpass=String.valueOf(con);
       
       if(name.isEmpty())
           JOptionPane.showMessageDialog(null,"Please Enter Name");
       else if(!isValidEmail(email))    
            JOptionPane.showMessageDialog(null,"Please Enter Valid Email Id");
       else if(!isValidMobile(mobile))
           JOptionPane.showMessageDialog(null,"Please Enter Valid Mobile Number");
       else if (address.isEmpty())
            JOptionPane.showMessageDialog(null,"Please Enter Address");    
       else if(username.isEmpty())    
              JOptionPane.showMessageDialog(null,"Please Enter Username");    
       else if(password.isEmpty())    
              JOptionPane.showMessageDialog(null,"Please Enter Password");   
       else if(conpass.isEmpty())    
              JOptionPane.showMessageDialog(null,"Please Enter Confirm Password");   
       else if(!password.equals(conpass))
                JOptionPane.showMessageDialog(null,"Password And Confirm Password Is Not Matched Please Re-Enter Correct Password"); 
       else
       {
           
          EditProfile ep=new  EditProfile();
           if(ep.isUpdate(st, name, email, mobile, address, username, password))
             JOptionPane.showMessageDialog(null,"User Data Updated Sucessfully");   
           else
                JOptionPane.showMessageDialog(null,"Error In Updation");   
    }                                        
    }//GEN-LAST:event_jButton3ActionPerformed

